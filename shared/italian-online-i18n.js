  // NOTE: which Worker answers are definitive is decided by the table in shared/italian-online-two-player-ui.js (independent of this module,
  // so a missing/failed translation file can never change how a Worker refusal is classified). This module only holds the WORDS.
  // Worker error codes that are deliberately NOT definitive (outcome unknown / not a user-facing refusal of a move).
  const UNKNOWN_WORKER_CODES = Object.freeze([
    "italian_write_uncertain", "italian_server_unavailable", "italian_read_unavailable", "italian_dependencies_missing",
    "italian_presence_not_proven", "italian_absence_rejected",
    // Stage F-A: POST /italian/end (void / resign / draw) - the room is read again after these; they are shown by END_REFUSED in the UI module
    "italian_draw_not_agreed", "italian_end_rejected",
    // STEP K3: kind "timeout" refusals (the room is read again; shown by END_REFUSED)
    "italian_timer_off", "italian_time_not_expired"
  ]);

  let provider = null;
  const listeners = [];
  function normalize(v) {
    if (typeof v !== "string") return null;
    const base = v.trim().toLowerCase().split(/[-_]/)[0];
    return LANGS.indexOf(base) !== -1 ? base : null;
  }
  function setLanguageProvider(fn) { provider = typeof fn === "function" ? fn : null; }
  function language() {
    let v = null;
    try { v = provider ? normalize(provider()) : null; } catch (_) { v = null; }
    return v || "ru";
  }
  function placeholders(text) {
    const out = [], re = /\{([A-Za-z0-9_]+)\}/g;
    let m; while ((m = re.exec(String(text))) !== null) out.push(m[1]);
    return out.sort();
  }
  function fill(template, params, lang) {
    return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, function (all, name) {
      if (!params || !Object.prototype.hasOwnProperty.call(params, name)) return all;   // missing parameter: leave the placeholder visible
      const v = params[name];
      return isMsg(v) ? render(v, lang) : String(v === null || v === undefined ? "" : v);
    });
  }
  function isMsg(v) { return !!v && typeof v === "object" && typeof v.k === "string"; }
  function lookup(lang, key) {
    const d = DICT[lang];
    if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
    if (Object.prototype.hasOwnProperty.call(DICT.ru, key)) return DICT.ru[key];
    return null;
  }
  function t(key, params, lang) {
    lang = lang || language();
    const raw = lookup(lang, key);
    return raw === null ? String(key) : fill(raw, params, lang);
  }
  function msg(key, params) { return Object.freeze({ k: key, p: params || null }); }
  function render(m, lang) {
    if (typeof m === "string") return m;
    if (!isMsg(m)) return "";
    return t(m.k, m.p, lang);
  }
  function onLanguageChange(fn) { if (typeof fn === "function" && listeners.indexOf(fn) === -1) listeners.push(fn); }
  function languageChanged() {
    for (const fn of listeners.slice()) { try { fn(language()); } catch (_) { /* one failing listener must not stop the others */ } }
  }
  // Static markup: data-it86-i18n (text), data-it86-i18n-aria (aria-label), data-it86-i18n-ph (placeholder).
  function applyStatic(rootEl) {
    if (!rootEl || typeof rootEl.querySelectorAll !== "function") return 0;
    let n = 0;
    rootEl.querySelectorAll("[data-it86-i18n]").forEach(function (el) { el.textContent = t(el.getAttribute("data-it86-i18n")); n++; });
    rootEl.querySelectorAll("[data-it86-i18n-aria]").forEach(function (el) { el.setAttribute("aria-label", t(el.getAttribute("data-it86-i18n-aria"))); n++; });
    rootEl.querySelectorAll("[data-it86-i18n-ph]").forEach(function (el) { el.setAttribute("placeholder", t(el.getAttribute("data-it86-i18n-ph"))); n++; });
    return n;
  }
  return Object.freeze({ LANGS, DICT, UNKNOWN_WORKER_CODES, setLanguageProvider, language, placeholders, t, msg, render,
    onLanguageChange, languageChanged, applyStatic });
