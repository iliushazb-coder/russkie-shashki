  function mergeInto(translations) {
    Object.keys(PACK).forEach(function (lang) {
      if (!translations[lang]) return;                 // язык ещё не заведён в игре -- пакет подождёт
      Object.keys(PACK[lang]).forEach(function (key) {
        if (!(key in translations[lang])) translations[lang][key] = PACK[lang][key];
      });
    });
  }

